def delete_game(game_id):
    db=get_db()

    game=db.execute(
        """
        SELECT *
        FROM games
        WHERE id=%s AND user_id=%s
        """,
        (
            game_id,
            session["user_id"]
        )
    ).fetchone()

    if game is None:
        return redirect(
            url_for("index")
        )

    image_path=game["image_path"]

    db.execute(
        """
        DELETE FROM games
        WHERE id=%s AND user_id=%s
        """,
        (
            game_id,
            session["user_id"]
        )
    )

    db.commit()

    try:
        delete_cover(image_path)
    except Exception:
        pass

    flash("Игра удалена 🗑️")

    return redirect(
        url_for("index")
    )


