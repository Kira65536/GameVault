@app.route(
    "/edit/<int:game_id>",
    methods=["GET","POST"]
)
@login_required
def edit_game(game_id):
    db=get_db()

    game=db.execute(
        """
        SELECT *
        FROM games
        WHERE id=%s AND user_id=%s
        """,
        (
            game_id,
            session["user_id"]
        )
    ).fetchone()

    if game is None:
        return redirect(
            url_for("index")
        )

    if request.method=="POST":
        name=request.form.get("name","").strip()
        genre=request.form.get("genre","").strip()
        rating_text=request.form.get("rating","").strip()
        status=request.form.get("status","").strip()
        description=request.form.get("description","").strip()
        image=request.files.get("image")

        if (
            not name
            or not genre
            or not rating_text
            or not status
            or not description
        ):
            return render_template(
                "edit_game.html",
                game=game,
                game_id=game_id,
                error="Заполни все поля"
            )

        try:
            rating=int(rating_text)

        except ValueError:
            return render_template(
                "edit_game.html",
                game=game,
                game_id=game_id,
                error="Рейтинг должен быть числом"
            )

        if rating<0 or rating>10:
            return render_template(
                "edit_game.html",
                game=game,
                game_id=game_id,
                error="Рейтинг должен быть от 0 до 10"
            )

        image_name=game["image"]

        if image is not None and image.filename!="":
            if not allowed_file(image.filename):
                return render_template(
                    "edit_game.html",
                    game=game,
                    game_id=game_id,
                    error="Разрешены PNG, JPG, JPEG и WEBP"
                )

            extension=Path(image.filename).suffix.lower()
            new_image_name=f"{uuid4().hex}{extension}"

            image.save(
                UPLOAD_FOLDER/new_image_name
            )

            old_image_path=UPLOAD_FOLDER/image_name

            if old_image_path.exists():
                old_image_path.unlink()

            image_name=new_image_name

        db.execute(
            """
            UPDATE games
            SET
                name=%s,
                genre=%s,
                rating=%s,
                status=%s,
                description=%s,
                image=%s
            WHERE id=%s AND user_id=%s
            """,
            (
                name,
                genre,
                rating,
                status,
                description,
                image_name,
                game_id,
                session["user_id"]
            )
        )

        db.commit()

        flash("Изменения сохранены ✅")

        return redirect(
            url_for(
                "game_details",
                game_id=game_id
            )
        )

    return render_template(
        "edit_game.html",
        game=game,
        game_id=game_id
    )


