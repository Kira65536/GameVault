@app.route("/")
@login_required
def index():
    search=request.args.get("q","").strip()
    status_filter=request.args.get("status","").strip()
    sort=request.args.get("sort","newest").strip()

    db=get_db()

    stats=db.execute(
        """
        SELECT
            COUNT(*) AS total,
            SUM(CASE WHEN status='Играю' THEN 1 ELSE 0 END) AS playing,
            SUM(CASE WHEN status='Пройдена' THEN 1 ELSE 0 END) AS completed,
            SUM(CASE WHEN status='Хочу пройти' THEN 1 ELSE 0 END) AS want,
            SUM(CASE WHEN status='Заброшена' THEN 1 ELSE 0 END) AS abandoned
        FROM games
        WHERE user_id=%s
        """,
        (session["user_id"],)
    ).fetchone()

    sql="""
        SELECT *
        FROM games
        WHERE user_id=%s
    """

    params=[session["user_id"]]

    if search:
        sql+=" AND name ILIKE %s"
        params.append(f"%{search}%")

    if status_filter:
        sql+=" AND status=%s"
        params.append(status_filter)

    sort_options={
        "newest":"id DESC",
        "oldest":"id ASC",
        "rating_high":"rating DESC",
        "rating_low":"rating ASC",
        "name_asc":"LOWER(name) ASC",
        "name_desc":"LOWER(name) DESC"
    }

    order_by=sort_options.get(
        sort,
        "id DESC"
    )

    sql+=f" ORDER BY {order_by}"

    rows=db.execute(
        sql,
        params
    ).fetchall()

    games=[
        (game["id"],game)
        for game in rows
    ]

    return render_template(
        "index.html",
        games=games,
        search=search,
        status_filter=status_filter,
        sort=sort,
        stats=stats
    )


@app.route("/add",methods=["GET","POST"])
@login_required
def add_game():
    if request.method=="POST":
        name=request.form.get("name","").strip()
        genre=request.form.get("genre","").strip()
        rating_text=request.form.get("rating","").strip()
        status=request.form.get("status","").strip()
        description=request.form.get("description","").strip()
        image=request.files.get("image")

        if (
            not name
            or not genre
            or not rating_text
            or not status
            or not description
        ):
            return render_template(
                "add_game.html",
                error="Заполни все поля"
            )

        try:
            rating=int(rating_text)

        except ValueError:
            return render_template(
                "add_game.html",
                error="Рейтинг должен быть числом"
            )

        if rating<0 or rating>10:
            return render_template(
                "add_game.html",
                error="Рейтинг должен быть от 0 до 10"
            )

        if image is None or image.filename=="":
            return render_template(
                "add_game.html",
                error="Выбери картинку"
            )

        if not allowed_file(image.filename):
            return render_template(
                "add_game.html",
                error="Разрешены PNG, JPG, JPEG и WEBP"
            )

        try:
            image_url,image_path=upload_cover(
                image,
                session["user_id"]
            )

        except Exception:
            return render_template(
                "add_game.html",
                error="Не удалось загрузить картинку"
            )

        db=get_db()

        try:
            db.execute(
                """
                INSERT INTO games(
                    name,
                    genre,
                    rating,
                    status,
                    description,
                    image,
                    image_path,
                    user_id
                )
                VALUES(%s,%s,%s,%s,%s,%s,%s,%s)
                """,
                (
                    name,
                    genre,
                    rating,
                    status,
                    description,
                    image_url,
                    image_path,
                    session["user_id"]
                )
            )

            db.commit()

        except Exception:
            db.rollback()

            try:
                delete_cover(image_path)
            except Exception:
                pass

            raise

        flash("Игра успешно добавлена 🎮")

        return redirect(
            url_for("index")
        )

    return render_template(
        "add_game.html"
    )


