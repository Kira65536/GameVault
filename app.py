@app.route(
    "/edit/<int:game_id>",
    methods=["GET","POST"]
)
@login_required
def edit_game(game_id):
    db=get_db()

    game=db.execute(
        """
        SELECT *
        FROM games
        WHERE id=%s AND user_id=%s
        """,
        (
            game_id,
            session["user_id"]
        )
    ).fetchone()

    if game is None:
        return redirect(
            url_for("index")
        )

    if request.method=="POST":
        name=request.form.get("name","").strip()
        genre=request.form.get("genre","").strip()
        rating_text=request.form.get("rating","").strip()
        status=request.form.get("status","").strip()
        description=request.form.get("description","").strip()
        image=request.files.get("image")

        if (
            not name
            or not genre
            or not rating_text
            or not status
            or not description
        ):
            return render_template(
                "edit_game.html",
                game=game,
                game_id=game_id,
                error="Заполни все поля"
            )

        try:
            rating=int(rating_text)

        except ValueError:
            return render_template(
                "edit_game.html",
                game=game,
                game_id=game_id,
                error="Рейтинг должен быть числом"
            )

        if rating<0 or rating>10:
            return render_template(
                "edit_game.html",
                game=game,
                game_id=game_id,
                error="Рейтинг должен быть от 0 до 10"
            )

        image_url=game["image"]
        image_path=game["image_path"]

        new_image_path=None
        old_image_path=image_path

        if image is not None and image.filename!="":
            if not allowed_file(image.filename):
                return render_template(
                    "edit_game.html",
                    game=game,
                    game_id=game_id,
                    error="Разрешены PNG, JPG, JPEG и WEBP"
                )

            try:
                image_url,new_image_path=upload_cover(
                    image,
                    session["user_id"]
                )

                image_path=new_image_path

            except Exception:
                return render_template(
                    "edit_game.html",
                    game=game,
                    game_id=game_id,
                    error="Не удалось загрузить картинку"
                )

        try:
            db.execute(
                """
                UPDATE games
                SET
                    name=%s,
                    genre=%s,
                    rating=%s,
                    status=%s,
                    description=%s,
                    image=%s,
                    image_path=%s
                WHERE id=%s AND user_id=%s
                """,
                (
                    name,
                    genre,
                    rating,
                    status,
                    description,
                    image_url,
                    image_path,
                    game_id,
                    session["user_id"]
                )
            )

            db.commit()

        except Exception:
            db.rollback()

            if new_image_path:
                try:
                    delete_cover(new_image_path)
                except Exception:
                    pass

            raise

        if new_image_path and old_image_path:
            try:
                delete_cover(old_image_path)
            except Exception:
                pass

        flash("Изменения сохранены ✅")

        return redirect(
            url_for(
                "game_details",
                game_id=game_id
            )
        )

    return render_template(
        "edit_game.html",
        game=game,
        game_id=game_id
    )


